import 'package:pos_machine/features/general_payments/domain/models/general_payment.dart';

const _prefixes = {
  'EXPENSE': 'EXP',
  'ASSET': 'AST',
  'INCOME': 'INC',
  'LOAN': 'LON',
  'LOAN_REPAY': 'LRP',
};

/// One row as the live list-general-payments API sends it.
Map<String, dynamic> paymentJson(int id,
        {String type = 'EXPENSE',
        String date = '2026-10-03',
        Object amount = 100,
        String? reference,
        String category = '8192',
        String categoryLabel = 'Transportation',
        int debitId = 15,
        String debit = 'Purchase Account',
        int creditId = 11,
        String credit = 'Cash Account',
        String status = 'SUCC'}) =>
    {
      'id': id,
      'reference_number':
          reference ?? '${_prefixes[type] ?? 'GP'}${'$id'.padLeft(5, '0')}',
      'entry_type': type,
      'entry_type_label': type == 'LOAN' ? 'Loan Received' : 'Label $type',
      'payment_date': date,
      'category': category,
      'category_label': categoryLabel,
      'description': null,
      'useful_life_years': null,
      'amount': amount,
      'payment_method': '7974',
      'payment_method_label': 'CASH',
      'expense_account_id': debitId,
      'expense_account_name': debit,
      'payment_account_id': creditId,
      'payment_account_name': credit,
      'status': status,
      'notes': null,
      'created_by': 11,
      'created_by_name': 'Admin',
      'created_at': '$date 08:00:00',
    };

GeneralPayment payment(int id,
        {String type = 'EXPENSE',
        String date = '2026-10-03',
        Object amount = 100,
        String category = '8192',
        String categoryLabel = 'Transportation',
        int debitId = 15,
        String debit = 'Purchase Account',
        int creditId = 11,
        String credit = 'Cash Account'}) =>
    GeneralPayment.fromJson(paymentJson(id,
        type: type,
        date: date,
        amount: amount,
        category: category,
        categoryLabel: categoryLabel,
        debitId: debitId,
        debit: debit,
        creditId: creditId,
        credit: credit));

/// One page in the live API shape: rows in `data`, paging in `pagination`.
Map<String, dynamic> apiPage(List<Map<String, dynamic>> rows,
        {int current = 1, int last = 1, int? total}) =>
    {
      'success': true,
      'message': 'General payments fetched successfully',
      'data': rows,
      'pagination': {
        'current_page': current,
        'last_page': last,
        'per_page': 100,
        'total': total ?? rows.length,
        'has_more_pages': current < last,
      },
    };

